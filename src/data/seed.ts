function makeBooking(
  index: number,
  overrides: Partial<Booking> & {
    roomTypeId: string;
    checkInOffset: number;
    nights: number;
    guestName: string;
    guestPhone: string;
    nightlyRate: number;
  }
): Booking {
  const checkIn = addDays(today, overrides.checkInOffset);
  const checkOut = addDays(today, overrides.checkInOffset + overrides.nights);
  const subtotal = overrides.nightlyRate * overrides.nights;
  const discountAmount = overrides.discountAmount ?? 0;
  const taxable = Math.max(0, subtotal - discountAmount);
  const gstRate = overrides.nightlyRate > 1000 ? 0.12 : 0;
  const gstAmount = Math.round(taxable * gstRate);
  const totalAmount = taxable + gstAmount;
  const num = String(1001 + index);
  return {
    id: `RN-2026-${num}`,
    invoiceNumber: `INV-RN-${num}`,
    roomTypeId: overrides.roomTypeId,
    roomNumber: overrides.roomNumber,
    checkIn,
    checkOut,
    nights: overrides.nights,
    guests: overrides.guests ?? 2,
    guestName: overrides.guestName,
    guestPhone: overrides.guestPhone,
    guestEmail:
      overrides.guestEmail ??
      `${overrides.guestName.toLowerCase().replace(/[^a-z]/g, '.')}@example.in`,
    idType: overrides.idType ?? 'Aadhaar',
    specialRequests: overrides.specialRequests ?? '',
    nightlyRate: overrides.nightlyRate,
    subtotal,
    discountAmount,
    promoCode: overrides.promoCode,
    gstRate,
    gstAmount,
    totalAmount,
    status: overrides.status ?? 'Confirmed',
    paymentStatus: overrides.paymentStatus ?? 'Paid',
    paymentMode: overrides.paymentMode ?? 'UPI',
    source: overrides.source ?? 'Direct Web',
    createdAt: addDays(today, Math.min(-1, overrides.checkInOffset - 2)) + 'T10:15:00.000Z',
    updatedAt: TODAY_ISO + 'T08:00:00.000Z',
  };
}

